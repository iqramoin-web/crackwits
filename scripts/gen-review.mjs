// Builds REVIEW.md — the checklist of every draft assumption and AI placeholder
// image across the case studies — from src/content/case-studies/*.ts.
import { mkdtempSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import ts from "typescript";

const root = join(import.meta.dirname, "..");
const dir = join(root, "src/content/case-studies");
const out = mkdtempSync(join(tmpdir(), "cw-review-"));

const studies = [];
for (const file of readdirSync(dir).filter((f) => f.endsWith(".ts") && f !== "index.ts")) {
  const js = ts.transpileModule(readFileSync(join(dir, file), "utf8"), {
    compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2020 },
  }).outputText;
  const target = join(out, file.replace(/\.ts$/, ".mjs"));
  writeFileSync(target, js);
  studies.push((await import(pathToFileURL(target).href)).default);
}

const images = (s) => {
  const list = [];
  if (s.cover.ai) list.push(s.cover.src);
  for (const section of s.sections) for (const m of section.media) if (m.ai && m.src) list.push(m.src);
  return [...new Set(list)];
};

const drafts = studies.filter((s) => s.draft).sort((a, b) => a.name.localeCompare(b.name));
const lines = [
  "# Case study review checklist",
  "",
  "Generated by `node scripts/gen-review.mjs`. Every item below is a drafting assumption or a temporary",
  "AI-generated asset. Verify or replace each one, then set `draft: false` on the case study",
  "(draft pages show a review badge and are `noindex`).",
  "",
  `Drafts: ${drafts.length} of ${studies.length} case studies.`,
  "",
];
for (const s of drafts) {
  lines.push(`## ${s.name} — \`src/content/case-studies/${s.slug}.ts\``, "");
  lines.push("**Assumptions to verify**", "");
  for (const item of s.review) lines.push(`- [ ] ${item}`);
  lines.push("", "**Metrics** — all shown as “—” until real figures are supplied:", "");
  for (const stat of s.stats) lines.push(`- [ ] ${stat.label}`);
  lines.push("", "**AI placeholder images to replace**", "");
  for (const src of images(s)) lines.push(`- [ ] \`public${src}\``);
  lines.push("");
}
writeFileSync(join(root, "REVIEW.md"), lines.join("\n"));
console.log(`REVIEW.md: ${drafts.length} drafts`);
